#!/bin/bash
# Regenerate Dockerfile.railway from the stock Dockerfile, so upstream image
# changes carry over and the stock image stays untouched.
set -euo pipefail
cd "$(dirname "$0")/.."
{
    echo "# GENERATED by railway/generate-dockerfile.sh from Dockerfile. Do not edit."
    sed -E '0,/^FROM python:[^ ]+$/{/^FROM python:[^ ]+ AS builder$/!s/^(FROM python:[^ ]+)$/\1 AS runtime/}' Dockerfile
    cat railway/Dockerfile.tail
} > Dockerfile.railway
grep -q "AS runtime" Dockerfile.railway || { echo "runtime stage not found" >&2; exit 1; }
